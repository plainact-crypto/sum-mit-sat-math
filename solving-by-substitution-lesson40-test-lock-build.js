'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const source = path.join(__dirname, 'solving-by-substitution-test.html');
const target = path.join(__dirname, 'dist/algebra/systems-of-linear-equations/solving-by-substitution/test/index.html');
let html = fs.readFileSync(source, 'utf8');
const hook = "document.getElementById('submit').onclick=()=>{";
if (!html.includes(hook)) throw new Error('Lesson 40 test submit hook missing');
if ((html.match(/level:'(?:EASY|EASY-MEDIUM|MEDIUM|HARD|HARD \/ EXAM-STYLE)'/g)||[]).length !== 5) throw new Error('Lesson 40 must have exactly five progressive test questions');
const guard = "let submitted=false;document.getElementById('submit').onclick=()=>{if(submitted)return;submitted=true;const button=document.getElementById('submit');button.disabled=true;button.textContent='Test Submitted';document.querySelectorAll('input[type=\"radio\"]').forEach(input=>input.disabled=true);";
html = html.replace(hook, guard);
if (!html.includes('if(submitted)return') || !html.includes('button.disabled=true')) throw new Error('Submit-once guard was not applied');
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
if (!scripts.length) throw new Error('No inline test JavaScript found');
for (const [,js] of scripts) new vm.Script(js);
fs.mkdirSync(path.dirname(target), {recursive:true});
fs.writeFileSync(target, html);
console.log('[lesson40] five-question test: submit-once guard, input freeze, and JavaScript syntax verified');
