'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const load=n=>fs.readFileSync(require('path').join(__dirname,n),'utf8');
const data=require('./finding-x-intercept-lesson12-qa-data.json');
const practice=load('finding-x-intercept-problems.html'),answers=load('finding-x-intercept-answers.html'),test=load('finding-x-intercept-test.html');
const p=practice.match(/const groups=(\[[\s\S]*?\]);let n=0;/);
const t=test.match(/const qs=(\[[\s\S]*?\]);const root=/);
assert(p&&t,'Cannot parse practice/test data');
const groups=vm.runInNewContext(p[1]),questions=vm.runInNewContext(t[1]);
assert.deepStrictEqual(groups.map(g=>g[2].length),[3,8,5,2]);
const all=groups.flatMap(g=>g[2]);
assert.strictEqual(all.length,18);
assert.strictEqual((answers.match(/class="answer"/g)||[]).length,18);
const letters=[...answers.matchAll(/class="final">Answer: ([A-D])\)/g)].map(x=>x[1]);
assert.strictEqual(letters.length,18);
all.forEach((q,i)=>{const [a,c]=data.practice.coeff[i],x=data.practice.values[i];assert.strictEqual(q[2],data.practice.choice[i]);assert.strictEqual(letters[i],'ABCD'[q[2]]);if(x===null){assert.strictEqual(a,0);assert(i===9?c!==0:c===0)}else assert(Math.abs(a*x+c)<1e-9,'Practice '+(i+1))});
assert.strictEqual(questions.length,5);
questions.forEach((q,i)=>{const [a,c]=data.test.coeff[i];assert.strictEqual(q.a,data.test.choice[i]);assert(Math.abs(a*data.test.values[i]+c)<1e-9,'Test '+(i+1))});
console.log('[Lesson 12] 18 practice + 18 aligned answers + 5 test QA PASS');
