tests.forEach((item,i)=>{
 assert(Math.abs(independent[i]-expectedNumerical[i])<1e-9,'Independent test math '+(i+1));
 assert.equal(item.c[item.a],expectedChoices[i],'Test choice '+(i+1));
 assert.equal(item.level,expectedLevels[i],'Test progression '+(i+1));
});
