const groups=JSON.parse(p.match(/const groups=(\[[\s\S]*?\]);let n=0;/)[1]);
const questions=groups.flatMap(g=>g[2]);
assert.equal(groups.map(g=>g[2].length).join(','),'3,8,5,2');
const correct=[1,2,1,1,1,2,0,1,3,2,1,1,1,1,1,0,2,1];
